import type { Review } from "@/lib/types";

/**
 * Every row here carries is_seed: true.
 *
 * These are development fixtures. They are not customer statements and are
 * never presented as such. Publishing invented text as a genuine review is a
 * misleading commercial practice under § 5 UWG, so the flag is checked in
 * three places: the query layer refuses to serve seed rows unless demo mode is
 * explicitly on, the rating calculation excludes them, and the interface
 * labels every screen on which they appear.
 */

let counter = 0;
const id = () => `rev-${String(++counter).padStart(4, "0")}`;

interface SeedInput {
  software_id: string;
  reviewer_name: string;
  reviewer_job_title: string;
  reviewer_company: string | null;
  reviewer_industry: string;
  reviewer_company_size: Review["reviewer_company_size"];
  used_for_duration: string;
  overall_rating: number;
  ease_of_use: number;
  value_for_money: number;
  customer_service: number;
  functionality: number;
  review_title: string;
  summary: string;
  pros: string;
  cons: string;
  review_date: string;
  helpful_count: number;
  verified_badge?: string | null;
  vendor_response?: string | null;
  vendor_response_date?: string | null;
}

function seed(input: SeedInput): Review {
  return {
    id: id(),
    reviewer_country: "DE",
    verified_badge: input.verified_badge ?? null,
    vendor_response: input.vendor_response ?? null,
    vendor_response_date: input.vendor_response_date ?? null,
    status: "published",
    is_seed: true,
    ...input,
  };
}

